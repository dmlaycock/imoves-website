#!/usr/bin/env python3
"""Build the Cloudflare Pages upload folder (dist/) from the repo.

- Copies the live site only: the frozen /version-*/ folders, tools/, .github/ and README stay on
  GitHub (GitHub Pages at dmlaycock.github.io/imoves-website keeps serving them).
- Writes a Cloudflare `_redirects` file from the meta-refresh stub pages, so legacy URLs answer
  with a real 301 instead of a 0-second refresh (the stubs stay too, as a fallback).
- Fails if any file is over Cloudflare Pages' 25 MiB limit or the file count is over 20,000.
Usage: python3 tools/build-dist.py [dist]
"""
import os, re, shutil, sys, glob
from urllib.parse import urljoin

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, sys.argv[1] if len(sys.argv) > 1 else 'dist')
EXCLUDE = re.compile(r'^(version-[a-z]|tools|\.github|dist|node_modules|\.git)(/|$)|^(README\.md|\.nojekyll)$')

if os.path.exists(DIST): shutil.rmtree(DIST)
count = 0; too_big = []
for dirpath, dirs, files in os.walk(ROOT):
    rel = os.path.relpath(dirpath, ROOT); rel = '' if rel == '.' else rel
    dirs[:] = [d for d in dirs if not EXCLUDE.match(os.path.join(rel, d))]
    for f in files:
        r = os.path.join(rel, f)
        if EXCLUDE.match(r): continue
        src = os.path.join(dirpath, f); dst = os.path.join(DIST, r)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst); count += 1
        if os.path.getsize(src) > 25 * 1024 * 1024: too_big.append((r, os.path.getsize(src)))

# _redirects from the meta-refresh stubs
rules = []
for f in sorted(glob.glob(os.path.join(DIST, '**', 'index.html'), recursive=True)):
    html = open(f, encoding='utf-8', errors='ignore').read(4000)
    m = re.search(r'http-equiv="refresh"[^>]*content="\d+;\s*url=([^"]+)"', html, re.I)
    if not m: continue
    path = '/' + os.path.relpath(os.path.dirname(f), DIST).replace(os.sep, '/')
    target = m.group(1).strip()
    if not target.startswith('http'):
        target = urljoin(path + '/', target)
        if not target.endswith('/') and '.' not in target.rsplit('/', 1)[-1]: target += '/'
        target = re.sub(r'/+$', '/', target) if target != '/' else target
    rules.append(f'{path}  {target}  301')
    rules.append(f'{path}/  {target}  301')
open(os.path.join(DIST, '_redirects'), 'w').write('# Legacy URLs (generated by tools/build-dist.py from the redirect stub pages)\n' + '\n'.join(rules) + '\n')

# Point every absolute link at the live address. The repo keeps the GitHub Pages address so link
# previews work on the preview; the live build must not (issues log #4).
PREVIEW, LIVE = 'https://dmlaycock.github.io/imoves-website', 'https://imoves.com'
swapped = 0
for dirpath, _, files in os.walk(DIST):
    for f in files:
        if not f.endswith(('.html', '.xml', '.txt', '.json', '.js', '.css', '.webmanifest')): continue
        fp = os.path.join(dirpath, f)
        s = open(fp, encoding='utf-8', errors='surrogateescape').read()
        if PREVIEW in s:
            swapped += s.count(PREVIEW)
            open(fp, 'w', encoding='utf-8', errors='surrogateescape').write(s.replace(PREVIEW, LIVE))
leftover = [os.path.relpath(os.path.join(d, f), DIST) for d, _, fs in os.walk(DIST) for f in fs
            if f.endswith('.html') and 'dmlaycock.github.io' in open(os.path.join(d, f), encoding='utf-8', errors='ignore').read()]

# sitemap.xml from the pages that are actually published (issues log #5): every real page, no
# forwards, no 404, and none of the pages people only reach after doing something.
import subprocess, datetime
NOT_LISTED = re.compile(r'^/(404|thank-you[^/]*|thanks-for-subscribing|message-sent|unsubscribe)$')
TOP = {'/', '/pricing', '/active-school', '/active-learning', '/active-blasts', '/primary-pe', '/dance', '/mats',
       '/cpd-for-primary-school-teachers', '/about-us', '/contact-us'}
def lastmod(src):
    try:
        d = subprocess.run(['git', '-C', ROOT, 'log', '-1', '--format=%cs', '--', src], capture_output=True, text=True).stdout.strip()
        return d or datetime.date.today().isoformat()
    except Exception:
        return datetime.date.today().isoformat()
urls = []
for f in sorted(glob.glob(os.path.join(DIST, '**', 'index.html'), recursive=True)):
    if 'http-equiv="refresh"' in open(f, encoding='utf-8', errors='ignore').read(4000): continue
    rel = os.path.relpath(os.path.dirname(f), DIST).replace(os.sep, '/')
    path = '/' if rel == '.' else '/' + rel
    if NOT_LISTED.match(path): continue
    src = os.path.relpath(os.path.join(ROOT, os.path.relpath(f, DIST)), ROOT)
    pri = '1.0' if path == '/' else ('0.9' if path in TOP else '0.7')
    loc = LIVE + ('/' if path == '/' else path)
    urls.append(f'  <url>\n    <loc>{loc}</loc>\n    <lastmod>{lastmod(src)}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>{pri}</priority>\n  </url>')
open(os.path.join(DIST, 'sitemap.xml'), 'w').write('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + '\n'.join(urls) + '\n</urlset>\n')

print(f'dist: {count} files, {len(rules)//2} redirects, {swapped} preview links switched to {LIVE}, sitemap {len(urls)} pages')
if leftover:
    print('PREVIEW ADDRESS STILL PRESENT in:', leftover[:5]); sys.exit(1)
if too_big:
    for r, s in too_big: print(f'TOO BIG for Cloudflare Pages (25 MiB): {r} {s/1e6:.1f} MB')
    sys.exit(1)
if count > 20000:
    print('TOO MANY files for Cloudflare Pages (20,000)'); sys.exit(1)
